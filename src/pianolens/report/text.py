def confidence_notes(rep: dict) -> list[str]:
    """Plain statements of what limits the confidence of this report."""
    out = []
    inp, refs, conf = rep["input"], rep["references"], rep["confidence"]
    prov = inp["provenance"]
    if conf["velocity"] == "low":
        if prov not in ("disklavier", "sensor"):
            why = f"the input is {prov} MIDI, not a direct key-sensor capture"
        else:
            why = ("the expert references for loudness are transcribed from audio (fewer than 8 "
                   "Disklavier or sensor recordings are available for this piece), and "
                   "transcription compresses loudness")
        out.append(f"Velocity (loudness) is low confidence: {why}. Loudness findings are shown "
                   "but are not used in \"What to practise\" (DECISIONS, after D-10).")
    if conf.get("transcribed"):
        lo, hi = cal.TRANSCRIBED_ERROR_RATE
        out.append(f"Transcribed input roughly doubles the apparent note-error rate "
                   f"({lo:.3f} to {hi:.3f} in D-10), so single flagged notes may be "
                   "transcription errors.")
    if conf.get("alignment_suspect"):
        mr = rep["correctness"].get("match_ratio")
        out.append(f"Only {_pct(mr)} of the notes could be matched to the score: the score may "
                   "not be the version that was played, so every finding is unreliable.")
    if not refs.get("tier_d_total"):
        out.append("No expert reference performances were available: tempo, loudness and timing "
                   "are shown without an expert comparison.")
    mf = refs.get("beat_map_mapped_fraction")
    if _ok(mf) and mf < 0.9:
        out.append(f"Only {_pct(mf)} of this score could be matched to the reference edition; "
                   "bars outside it have no expert band.")
    cs = rep["correctness"]
    if not cs.get("extras_counted", True):
        out.append("Extra notes are low confidence on transcribed input (A-01: phone recordings "
                   "produced many extra notes that were not played). They are shown in the "
                   "timeline but are not ranked and never become practise items.")
    if cs.get("fast_repeat_low_confidence") and cs.get("n_missed_fast_repeat"):
        ms = int(round(1000 * cs.get("fast_repeat_max_ioi_sec", cal.FAST_REPEAT_MAX_IOI_SEC)))
        out.append(f"{_n(cs['n_missed_fast_repeat'], 'missed note')} fall on fast repeated notes "
                   f"(the same key again within {ms} ms). Transcription often merges such "
                   "repeats into one note (BL-21), so these are low confidence: shown in the "
                   "timeline, not ranked.")
    for nh in cs.get("not_heard") or []:
        out.append(not_heard_text(nh))
    xc = cs.get("expert_check") or {}
    if xc:
        who = expert_words(xc.get("provenance"))
        if xc.get("n_bars_checked"):
            out.append(f"Per-bar expert check: each bar's flagged notes were compared with "
                       f"{xc['n_expert_performances']} {who} of this score. Bars with no more "
                       "errors than experts show there are not ranked (likely score, edition or "
                       "checker artefacts).")
        else:
            out.append(f"No per-bar expert check: {xc.get('n_expert_performances', 0)} {who} "
                       f"of this score were available ({xc.get('min_refs', 5)} needed), so "
                       "flagged bars may include score or edition artefacts.")
    ec = rep["correctness"].get("expert_calibration", {})
    out.append(f"The note checker also flags notes in expert recordings: in a typical expert "
               f"performance {_pct(ec.get('share_bars_with_error_median', float('nan')))} of "
               "bars have at least one flagged note (real slips plus alignment noise). Only "
               "bars beyond what experts show are ranked.")
    out.append("Control measures (timing steadiness, evenness, pedal) describe this playing "
               "against experts; they are not yet validated as measures of skill (D-10).")
    return out


