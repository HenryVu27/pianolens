def _correctness_card(rep: dict) -> dict:
    c = rep["correctness"]
    ec = c.get("expert_calibration", {})
    graded = c["n_score_notes"] - c.get("n_interpolated", 0)
    f = [f"{c['n_correct']} of {graded} score notes were played as written "
         f"({_pct(c['accuracy'], 1)}).",
         f"Flagged: {_n(c['n_wrong_pitch'], 'wrong note')}, {_n(c['n_missed'], 'missed note')} "
         f"and {_n(c['n_extra'], 'extra note')}, in {c['n_bars_with_errors']} of "
         f"{c['n_bars']} bars."]
    er = c.get("error_rate")
    if _ok(er):
        s = (f"Error rate {_pct(er, 1)}. On expert recordings this checker reports a median of "
             f"{_pct(ec['error_rate_q50'], 1)} (95% of experts below "
             f"{_pct(ec['error_rate_q95'], 1)}).")
        t = c.get("error_rate_tier", "none")
        if t != "none":
            s += f" Yours is higher than {TIER_PCT[t]} of expert performances."
        f.append(s)
    worst = sorted((b for b in rep["bars"] if not b["correctness"].get("not_heard")),
                   key=lambda b: -b["correctness"]["n_errors"])[:3]
    worst = [b for b in worst if b["correctness"]["n_errors"] > 0]
    if worst:
        f.append("Most flagged notes: " + ", ".join(
            f"bar {b['label']} ({b['correctness']['n_errors']})" for b in worst) + ".")
    ns, nn = c.get("n_bars_strong", 0), c.get("n_bars_notable", 0)
    f.append(f"Bars beyond the expert range: {ns} strong, {nn} notable (missed notes are "
             "judged per bar, not per note).")
    for nh in c.get("not_heard") or []:
        f.append(not_heard_text(nh))
    if c.get("fast_repeat_low_confidence") and c.get("n_missed_fast_repeat"):
        f.append(f"Not ranked: {_n(c['n_missed_fast_repeat'], 'missed note')} on fast repeated "
                 "notes (low confidence on transcribed input).")
    xc = c.get("expert_check") or {}
    sup = xc.get("bars_suppressed") or []
    if sup:
        f.append(f"Not ranked, {_n(len(sup), 'bar')} that {artefact_text(rep)}: "
                 + ", ".join(sup[:12]) + ("..." if len(sup) > 12 else "") + ".")
    tk = rep.get("takes")
    if tk and tk.get("takes"):
        rec = tk["recurring_error_bars"]
        s = (f"Across {tk['n_takes']} takes, the same wrong note recurs in "
             + (_n(len(rec), "bar") + ": " + ", ".join(rec[:12]) if rec else "no bar") + ".")
        if tk.get("promoted"):
            s += (f" Checked against {tk['n_expert_checks']} expert recordings of this score, "
                  "so checker artefacts are removed." + (
                      " A mistake repeated across takes is learned, not a slip, so these bars "
                      "are marked strong." if rec else ""))
        elif rec:
            s += (" Fewer than two expert recordings of this score were available to rule out "
                  "checker artefacts, so these bars are not marked strong.")
        f.append(s)
    return {"title": "Correctness", "findings": f}


def _control_card(rep: dict) -> dict:
    f = []
    t, c = rep.get("timing") or {}, rep["control"]
    if _ok(t.get("noise_rms_ms")):
        nt = sum(1 for b in rep["bars"] if b["timing"]["tier"] != "none")
        ns = sum(1 for b in rep["bars"] if b["timing"]["tier"] == "strong")
        f.append(f"Timing steadiness: your note timing departs from the expert timing pattern "
                 f"by {t['noise_rms_ms']:.0f} ms RMS ({t['noise_rms_beats']:.3f} beats), "
                 f"against {t.get('n_references', 0)} reference performances; "
                 f"{nt} bars are outside the expert range ({ns} strongly).")
    elif _ok(c.get("jitter_nometric_rms_ms")):
        f.append(f"Timing steadiness (no references): {c['jitter_nometric_rms_ms']:.0f} ms RMS "
                 "after removing your own recurring within-bar pattern.")
    if c.get("even_strict_n_runs"):
        runs = [r for r in rep.get("evenness_runs", []) if _ok(r.get("ioi_cv"))]
        s = (f"Evenness in {_n(int(c['even_strict_n_runs']), 'scale or figure passage')}: "
             f"timing varies by {c['even_strict_ioi_cv']:.2f} of the note length (CV) at "
             f"{c['even_strict_note_rate_nps']:.1f} notes per second; loudness by "
             f"{c['even_strict_vel_sd_midi']:.1f} velocity units (SD).")
        near = sorted({lab for r in runs for lab in r.get("literature_similar_rate", [])})
        rates = [e["note_rate_nps"] for e in cal.LITERATURE_EVENNESS]
        if near:
            ents = [e for e in cal.LITERATURE_EVENNESS if e["label"] in near]
            nr = sum(1 for r in runs if r.get("literature_similar_rate"))
            s += (f" {_n(nr, 'passage')} run at a speed where published values exist: "
                  + "; ".join(f"{e['label'].lower()} at {e['note_rate_nps']} notes per second, "
                              f"CV about {e['ioi_cv_lo']:.2f}"
                              + (f"-{e['ioi_cv_hi']:.2f}" if e["ioi_cv_hi"] != e["ioi_cv_lo"]
                                 else "") + f" ({e['source']})" for e in ents)
                  + ". These come from instructed scales, so they are a floor, not a norm.")
        else:
            s += (f" Published values come from instructed scales at {min(rates):.1f} to "
                  f"{max(rates):.1f} notes per second, so none is at your note rate; unevenness "
                  "rises with speed, so they are not compared here.")
        lo, hi = cal.VELOCITY_JND_MIDI
        s += f" For scale, listeners notice loudness steps of about {lo} to {hi} velocity units."
        f.append(s)
    if _ok(c.get("hand_async_median_ms")):
        m = c["hand_async_median_ms"]
        side = "left hand" if m > 0 else "right hand"
        f.append(f"Hands together: at shared onsets the {side} typically sounds first, by "
                 f"{abs(m):.0f} ms (median); after allowing for the louder hand sounding "
                 f"earlier, the spread is {c['hand_async_resid_sd_ms']:.0f} ms (SD). "
                 "Asynchronies within about 30 ms are hard to hear (Goebl et al. 2009).")
    if c.get("pedal_available") and _ok(c.get("pedal_blur_fraction")):
        s = (f"Pedal: held through {_pct(c['pedal_blur_fraction'])} of "
             f"{int(c['n_harmony_changes'])} detected harmony changes (detector F1 0.76 against "
             "annotated harmony).")
        if not c.get("n_pedal_references"):
            s += " No expert pedal data exist for this score, so this is not compared."
        f.append(s)
    elif not c.get("pedal_available"):
        f.append("Pedal: no pedal data in this file.")
    return {"title": "Control", "findings": f}


#: Disclosures for LLM phrase boundaries (DECISIONS 2026-09-28; F-05e; BL-17 and its audit).
#: ``genre_untested`` is a template filled with the block's ``untested_genre``.
PHRASE_CAVEATS = {
    "romantic": ("Caution: on Romantic character pieces, this language model's blind readings "
                 "matched expert (DCML) phrase ends at about 0.64 on average (plausible range "
                 "0.55-0.72), below the project's 0.70 bar, and from 0.14 to 0.92 on single "
                 "pieces (BL-17, 24 pieces); the cadence detector reached 0.31. The phrase-tempo "
                 "measure itself also fell short of its expert-boundary level on Romantic pieces "
                 "(F-05e, 3 pieces)."),
    "style_unvalidated": ("Caution: these boundaries were validated only on Classical sonatas "
                          "and Romantic character pieces (R-08, F-05e, BL-17)."),
    "compound_meter": ("Caution: this piece is in a compound meter (e.g. 6/8 or 6/4), where the "
                       "language-model boundaries are not validated: BL-17 had only 6 such "
                       "pieces (6/8 and 12/8, none by Chopin, none in 6/4), a descriptive "
                       "result (mean 0.65, range 0.46-0.85)."),
    "genre_untested": ("Caution: this piece is a {genre}; no {genre} was among the pieces the "
                       "boundaries were tested on (nocturnes and waltzes never were; BL-17 used "
                       "Chopin mazurkas, Grieg Lyric Pieces and a few Schumann, Tchaikovsky and "
                       "Liszt pieces)."),
}

#: Always added to the phrase-tempo finding (DF-02 / BL-17 audit).
PHRASE_DESCRIPTIVE = "No practice item depends on this measure."


def _phrase_tempo_text(p: dict) -> str:
    """The "Phrases in time" finding: the measure, where its boundaries come from, and (for LLM
    boundaries) the per-reading values, the cadence-detector value, the phrase-count ratio,
    whether the annotator recognised the piece, and the caveats. When the LLM and detector
    values differ in sign the item is labelled undetermined (BL-17 audit)."""
    llm = p.get("boundaries") == "llm"
    und = llm and bool(p.get("undetermined"))
    src = ("boundaries marked by a language model reading the score" if llm
           else "boundaries found from cadences")
    n = float(p.get("n_phrases") or 0)
    n_txt = f"{n:.0f}" if n == round(n) else f"{n:.1f} (mean over readings)"
    t = (f"Phrases in time{' (undetermined)' if und else ''}: {_pct(p['concave_share'])} of "
         f"{n_txt} phrases ({src}) slow at both ends; with the boundaries shifted by 2 bars the "
         f"share is {_pct(p['null_concave_share'])}, so the excess is "
         f"{100 * p['concave_excess']:+.0f} points.")
    if not llm:
        why = p.get("llm_fallback_reason")
        if why:
            t += f" No language-model phrase boundaries were used: {why}."
        return t + " " + PHRASE_DESCRIPTIVE
    runs = p.get("llm_runs") or []
    prov = p.get("llm_provenance") or {}
    if runs:
        t += (f" Boundaries: {prov.get('model') or 'LLM'}, mean of {len(runs)} independent "
              "blind readings (excess per reading " + ", ".join(
                  f"{100 * r['concave_excess']:+.0f}" for r in runs
                  if _ok(r.get("concave_excess"))) + " points).")
    if _ok(p.get("concave_excess_cadence")):
        t += (f" With cadence-detector boundaries the excess is "
              f"{100 * p['concave_excess_cadence']:+.0f} points.")
    if und:
        t += (" The two boundary sources disagree in direction, so whether the phrases slow at "
              "both ends more than chance is undetermined for this performance.")
    if _ok(p.get("phrase_count_ratio")):
        t += (f" Phrase count: {p['n_phrases']:.1f} phrases against "
              f"{p.get('n_phrases_cadence', 0):.0f} from the {p.get('phrase_count_reference')} "
              f"(ratio {p['phrase_count_ratio']:.2f}); the excess penalises correct but finer "
              "phrasing, so read it at this phrase level.")
    k, nr = prov.get("recognised_runs"), prov.get("n_runs")
    if k:
        t += (f" The annotator named the piece in {k} of {nr} readings, so remembered analyses "
              "may have shaped these boundaries.")
    for c in p.get("caveats") or ():
        if c in PHRASE_CAVEATS:
            t += " " + PHRASE_CAVEATS[c].format(genre=p.get("untested_genre") or "piece type")
    return t + " " + PHRASE_DESCRIPTIVE


def _shaping_card(rep: dict) -> dict:
    s = rep.get("shaping") or {}
    f = []
    for ch, what in (("velocity", "loudness"), ("articulation", "note lengths")):
        c = s.get(f"coherence_{ch}")
        if c and c.get("defined") and _ok(c.get("r2_no_markings")):
            r2 = c["r2_no_markings"]
            f.append(f"Structure in {what}: {_pct(max(r2, 0))} of the note-to-note variation "
                     f"is predictable from pitch, harmony, metre and phrase position in held-out "
                     f"bars (R² {r2:.2f}, dynamic markings left out).")
        elif c:
            f.append(f"Structure in {what}: not reported (too few bars for the check).")
    p = s.get("phrase_tempo")
    if p and _ok(p.get("concave_share")):
        f.append(_phrase_tempo_text(p))
    v = s.get("voicing")
    if v and _ok(v.get("vel_diff_mean_midi")):
        lead = v.get("lead_mean_ms")
        r = v.get("lead_vel_corr")
        f.append(f"Melody over accompaniment: the melody is louder at "
                 f"{_pct(v['frac_melody_louder'])} of shared onsets, by "
                 f"{v['vel_diff_mean_midi']:.1f} velocity units on average"
                 + (f", and sounds {abs(lead):.0f} ms {'early' if lead > 0 else 'late'}"
                    if _ok(lead) else "")
                 + (f" (timing and loudness difference correlate, r = {r:.2f})" if _ok(r) else "")
                 + ".")
    d = s.get("dynamics")
    if d and _ok(d.get("hairpin_agree_frac")):
        f.append(f"Written dynamics: {_pct(d['hairpin_agree_frac'])} of "
                 f"{int(d.get('hairpin_n', 0))} hairpins go the marked way"
                 + (f"; {_pct(d['level_agree_frac'])} of {int(d.get('level_n', 0))} level "
                    "changes (p, f, ...)" if _ok(d.get("level_agree_frac")) else "") + ".")
    f.append("Tempo coherence with the phrase structure is not reported: it needs annotated "
             "phrase boundaries (F-05b).")
    return {"title": "Shaping", "findings": f}


def _interp_card(rep: dict) -> dict:
    it = rep.get("interpretation") or {}
    f = []
    if not it:
        return {"title": "Interpretation", "findings": [
            "No expert comparison: no reference performances of this piece."]}
    to = it.get("tempo_overall", {})
    if _ok(to.get("ref_median")):
        f.append(f"Overall tempo over the bars you played: {to['target_bpm']:.0f} beats per "
                 f"minute; over the same bars the {to['n_refs']} reference performances run "
                 f"from {to['ref_q10']:.0f} to "
                 f"{to['ref_q90']:.0f} (10th to 90th percentile, median "
                 f"{to['ref_median']:.0f}). You are faster than {_pct(to['pct_refs_slower'])} "
                 "of them.")
    for ch, what in (("tempo", "Tempo shape"), ("velocity", "Loudness shape")):
        ns = sum(1 for b in rep["bars"] if b[ch]["tier"] == "strong")
        nn = sum(1 for b in rep["bars"] if b[ch]["tier"] == "notable")
        wins = [w for w in it.get("windows", []) if w["block"] == ch and w["status"] == "ok"]
        s = (f"{what}: {ns} bars strongly and {nn} notably outside the expert range "
             f"(out of {len(rep['bars'])}).")
        typ = [w for w in wins if _ok(w.get("typicality_pct"))]
        if typ:
            w = min(typ, key=lambda w: w["typicality_pct"])
            lab = _bars_list(rep, [w["bars"][0], w["bars"][-1]]).replace(", ", "-")
            s += (f" Least typical section: {lab}, where {_pct(w['typicality_pct'])} of "
                  "held-out experts are at least as unusual.")
        flat = [w for w in wins if w["flat_tier"] != "none"]
        ext = [w for w in wins if w["extreme_tier"] != "none"]
        if flat:
            s += f" Too flat in {_n(len(flat), 'section')}."
        if ext:
            s += f" More extreme than 95% of experts in {_n(len(ext), 'section')}."
        if ch == "velocity" and rep["confidence"]["velocity"] == "low":
            s += " (Low confidence, see the notes above.)"
        f.append(s)
    f.append("Individual choices outside the shared expert pattern are normal: experts share "
             "only a small part of their shaping (R-02). A flag says \"unusual here\", not "
             "\"wrong\".")
    f.append("Model-based quality ratings are not included: the rating model is still at "
             "single-rater reliability (R-04).")
    return {"title": "Interpretation", "findings": f}


def summary_findings(rep: dict) -> list[dict]:
    """The four summary cards, in report order. No overall grade."""
    return [_correctness_card(rep), _control_card(rep), _shaping_card(rep), _interp_card(rep)]
