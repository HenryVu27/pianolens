"""Template text for the practice report (F-08). Every sentence is filled from measured numbers
in the report data; nothing is generated by a language model (LLM wording is Phase 7).

Tier words: "strong" = beyond the experts' 99th percentile ("well outside the expert range"),
"notable" = beyond the 95th ("outside the usual expert range"). DECISIONS 2026-09-28.
"""

from __future__ import annotations

import math
from typing import Any

import numpy as np

from pianolens.report import calibration as cal

TIER_WORDS = {"strong": "well outside the expert range",
              "notable": "outside the usual expert range"}
TIER_PCT = {"strong": "99%", "notable": "95%"}


def _ok(x: Any) -> bool:
    try:
        return x is not None and math.isfinite(float(x))
    except (TypeError, ValueError):
        return False


_NAMES = ("C", "C#", "D", "Eb", "E", "F", "F#", "G", "Ab", "A", "Bb", "B")


def pitch_name(midi: int | None) -> str:
    """Scientific pitch name of a MIDI note number (60 = C4); sharps / flats as usual."""
    if midi is None:
        return "?"
    m = int(midi)
    return f"{_NAMES[m % 12]}{m // 12 - 1}"


def _pct(x: float, nd: int = 0) -> str:
    return f"{100 * x:.{nd}f}%"


def _n(k: int, word: str, plural: str | None = None) -> str:
    return f"{k} {word if k == 1 else (plural or word + 's')}"


def _bars_list(rep: dict, idx: list[int]) -> str:
    labels = [rep["bars"][i]["label"] for i in idx]
    if not labels:
        return ""
    return ("bar " if len(labels) == 1 else "bars ") + ", ".join(labels)


def _span_mean(rep: dict, idx: list[int], ch: str, key: str) -> float:
    v = [rep["bars"][i][ch].get(key) for i in idx]
    v = [float(x) for x in v if _ok(x)]
    return float(np.mean(v)) if v else float("nan")


def _window_for(rep: dict, block: str, idx: list[int]) -> dict | None:
    wins = rep.get("interpretation", {}).get("windows", [])
    best = None
    for w in wins:
        if w["block"] == block and set(idx) & set(w["bars"]):
            if best is None or {"strong": 2, "notable": 1}.get(w["flat_tier"], 0) > \
                    {"strong": 2, "notable": 1}.get(best["flat_tier"], 0):
                best = w
    return best


